const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();

function translateText(value: string, language: SiteLanguage) {
  const trimmed = value.trim();
  if (!trimmed || language === "en") return value;
  return Object.entries(translations)
    .sort(([first], [second]) => second.length - first.length)
    .reduce((result, [english, arabic]) => result.split(english).join(arabic), value);
}

export function applyLocalLanguage(language: SiteLanguage) {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode() as Text | null;
  while (node) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue ?? "");
    node.nodeValue = translateText(originalText.get(node) ?? "", language);
    node = walker.nextNode() as Text | null;
  }

  const translatableAttributes = ["placeholder", "aria-label", "title"];
  document.querySelectorAll<HTMLElement>("[placeholder], [aria-label], [title]").forEach((element) => {
    let saved = originalAttributes.get(element);
    if (!saved) {
      saved = new Map();
      originalAttributes.set(element, saved);
    }

    translatableAttributes.forEach((attribute) => {
      const current = element.getAttribute(attribute);
      if (current !== null && !saved!.has(attribute)) saved!.set(attribute, current);
      const original = saved!.get(attribute);
      if (original !== undefined) element.setAttribute(attribute, translateText(original, language));
    });
  });
}
